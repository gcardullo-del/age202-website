export function getCompletedAtp250(
  now = new Date(),
): Atp250LiveTournament[] {
  const today = new Date(
    Date.UTC(
      now.getUTCFullYear(),
      now.getUTCMonth(),
      now.getUTCDate(),
    ),
  );

  return atp250LiveRegistry.filter(
    (tournament) => {
      const endDate = new Date(
        `${tournament.endDate}T23:59:59.999Z`,
      );

      return endDate < today;
    },
  );
}
